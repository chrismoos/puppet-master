#!/usr/bin/env node
// Writes licenses/THIRD-PARTY.md from what the build actually resolves, so the
// inventory is regenerated rather than maintained by hand and cannot quietly
// drift from the lockfiles.
//
// Crates come from `cargo metadata`, which reads each package's own manifest.
// npm packages come from the installed tree, filtered to what is reachable at
// runtime: a build-time tool is not distributed, so its license carries no
// obligation on the binaries.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(repo, "licenses", "THIRD-PARTY.md");

function crates() {
  const json = execFileSync(
    "cargo",
    ["metadata", "--format-version", "1", "--all-features", "--locked"],
    { cwd: repo, encoding: "utf8", maxBuffer: 1 << 28 },
  );
  const meta = JSON.parse(json);
  return meta.packages
    .filter((p) => p.source)
    .map((p) => ({ name: p.name, version: p.version, license: p.license ?? "UNSTATED" }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

/** Packages the shipped web bundle can reach, which is what gets distributed. */
function webPackages() {
  // pnpm's own resolution, because its store layout means walking
  // node_modules/<name> by hand stops at the direct dependencies.
  const json = execFileSync(
    "pnpm",
    ["-F", "puppet-master-web", "-F", "@puppet-master/client-core", "list", "--prod", "--depth", "Infinity", "--json"],
    { cwd: repo, encoding: "utf8", maxBuffer: 1 << 28 },
  );
  const seen = new Map();
  const walk = (deps) => {
    for (const [name, node] of Object.entries(deps ?? {})) {
      const version = node.version ?? "";
      // A workspace link is our own code, not a third party's.
      if (version.startsWith("link:")) {
        walk(node.dependencies);
        continue;
      }
      const key = `${name}@${version}`;
      if (seen.has(key)) continue;
      seen.set(key, { name, version, license: licenseOf(node.path, name) });
      walk(node.dependencies);
    }
  };
  for (const workspace of JSON.parse(json)) walk(workspace.dependencies);
  return [...seen.values()].sort(
    (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

/** The license a package declares, read from where pnpm put it. */
function licenseOf(path, name) {
  const candidates = [path && join(path, "package.json"), join(repo, "node_modules", name, "package.json")];
  for (const manifest of candidates) {
    if (!manifest || !existsSync(manifest)) continue;
    try {
      const pkg = JSON.parse(readFileSync(manifest, "utf8"));
      if (typeof pkg.license === "string") return pkg.license;
      if (pkg.license?.type) return pkg.license.type;
    } catch {
      // fall through to the next candidate
    }
  }
  return "UNSTATED";
}

function table(rows) {
  const lines = ["| Package | Version | License |", "| --- | --- | --- |"];
  for (const row of rows) {
    lines.push(`| ${row.name} | ${row.version} | ${row.license} |`);
  }
  return lines.join("\n");
}

const rust = crates();
const web = webPackages();
const body = `# Third-party licenses

Generated by \`scripts/third-party-licenses.mjs\` from the resolved lockfiles.
Do not edit by hand: run \`make licenses\` after changing a dependency.

Obligations that follow from this list are summarized in [NOTICE](../NOTICE).

## Rust crates compiled into the binaries (${rust.length})

${table(rust)}

## npm packages reachable from the shipped web bundle (${web.length})

Build-time tooling is excluded: it is not distributed, so its license places no
obligation on the binaries.

${table(web)}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, body);
process.stdout.write(`wrote ${out}: ${rust.length} crates, ${web.length} npm packages\n`);
